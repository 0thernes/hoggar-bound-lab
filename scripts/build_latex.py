#!/usr/bin/env python3
"""
build_latex.py - a LaTeX source and PDF of paper/spectral-floor.md, for arXiv and journal submission.

  python scripts/build_latex.py --pandoc PATH --tectonic PATH

The Markdown file stays the canonical text.  This script converts it with pandoc, wraps the result in a
plain article preamble (XeLaTeX or LuaLaTeX: the Lean excerpt uses Unicode symbols), refits the tables to
the text width, copies the figures, and compiles with Tectonic.  Output, in publication/spectral-floor/:
spectral-floor.tex, figures/, spectral-floor.pdf, tectonic-output.log and build-record.json.
Nothing is submitted anywhere.
"""
import argparse, hashlib, json, os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "paper", "spectral-floor.md")
OUT = os.path.join(ROOT, "publication", "spectral-floor")

PREAMBLE = r"""% Generated by scripts/build_latex.py from paper/spectral-floor.md.  Compile with XeLaTeX or LuaLaTeX.
\documentclass[11pt,a4paper]{article}
\usepackage{fontspec}
\setmonofont{DejaVuSansMono.ttf}[Scale=0.82]
\usepackage[margin=1in]{geometry}
\usepackage{amsmath,amssymb}
\usepackage{graphicx}
\usepackage{longtable,booktabs,array,calc}
\usepackage{fvextra}
\usepackage{xurl}
\usepackage[colorlinks=true,linkcolor=black,citecolor=black,urlcolor=blue]{hyperref}
\RecustomVerbatimEnvironment{verbatim}{Verbatim}{breaklines=true,breakanywhere=true,fontsize=\footnotesize}
\providecommand{\tightlist}{\setlength{\itemsep}{0pt}\setlength{\parskip}{0pt}}
\providecommand{\pandocbounded}[1]{#1}
\newcommand{\lt}{<}
\newcommand{\gt}{>}
\setlength{\emergencystretch}{3em}
\setlength{\parskip}{0.45em}
\setlength{\parindent}{0pt}
\setcounter{secnumdepth}{0}
\renewcommand{\arraystretch}{1.15}
\makeatletter
\def\maxwidth{\ifdim\Gin@nat@width>\linewidth\linewidth\else\Gin@nat@width\fi}
\makeatother
\setkeys{Gin}{width=\maxwidth,keepaspectratio}
"""

BS = "\\"


def plain_len(cell):
    """rough printed length of a LaTeX cell"""
    c = re.sub(r"\\texttt\{([^{}]*)\}", lambda m: m.group(1), cell)
    c = re.sub(r"\\[A-Za-z]+", "x", c)
    c = re.sub(r"[{}$^_\\]", "", c)
    return max(len(c.strip()), 1)


def fit_tables(tex):
    """pandoc gives l-columns for GitHub tables; replace them by ragged p-columns that fill the line."""
    def one(m):
        ncol = len(m.group(1))
        body = m.group(2)
        rows = [r for r in re.split(r"\\\\\s*\n", body) if " & " in r]
        width = [1] * ncol
        for r in rows:
            cells = r.split(" & ")
            if len(cells) != ncol:
                continue
            for i, c in enumerate(cells):
                if i == 0:
                    c = c.split("\n")[-1]
                width[i] = max(width[i], min(plain_len(c), 90))
        weight = [max(w, 4) ** 0.72 for w in width]
        total = sum(weight)
        frac = [w / total for w in weight]
        # a column must hold its longest unbreakable \texttt{...} word (about 5.1pt per character of 452pt)
        need = [0.0] * ncol
        for r in rows:
            cells = r.split(" & ")
            if len(cells) != ncol:
                continue
            for i, c in enumerate(cells):
                for word in re.findall(r"\\texttt\{([^{}]*)\}", c):
                    longest = max(len(x) for x in word.replace(BS + "_", "_").split(" "))
                    need[i] = max(need[i], min(0.55, (5.1 * longest + 14) / 452.0))
        short = [i for i in range(ncol) if frac[i] < need[i]]
        if short:
            rest = 1.0 - sum(need[i] for i in short)
            other = sum(frac[i] for i in range(ncol) if i not in short)
            frac = [need[i] if i in short else frac[i] * rest / other for i in range(ncol)]
        spec = "".join(">{%sraggedright%sarraybackslash}p{(%slinewidth - %d%stabcolsep) * %sreal{%.4f}}"
                       % (BS, BS, BS, 2 * ncol - 2, BS, BS, f) for f in frac)
        size = BS + ("footnotesize" if ncol >= 6 else "small")
        return "{%s\n%sbegin{longtable}[]{@{}%s@{}}%s%send{longtable}\n}" % (size, BS, spec, body, BS)
    return re.sub(r"\\begin\{longtable\}\[\]\{@\{\}([lcr]+)@\{\}\}(.*?)\\end\{longtable\}", one, tex, flags=re.S)


def split_source(text):
    lines = text.split("\n")
    assert lines[0].startswith("# ")
    title = lines[0][2:].strip()
    i = 1
    while not lines[i].strip():
        i += 1
    subtitle = lines[i].strip().strip("*")
    i += 1
    while not lines[i].strip():
        i += 1
    byline = []
    while lines[i].strip():
        byline.append(lines[i].replace("<br>", "").strip())
        i += 1
    rest = "\n".join(lines[i:])
    a = rest.index("## Abstract")
    b = rest.index("## 1. Scope")
    note = rest[:a].strip()
    abstract = rest[a + len("## Abstract"):b].strip()
    body = rest[b:]
    return title, subtitle, byline, note, abstract, body


def prepare(md):
    # figure: image paragraph followed by an italic caption paragraph  ->  one image with that caption
    def fig(m):
        cap = re.sub(r"^Figure \d+\.\s*", "", m.group(2).strip())
        return "![%s](%s)" % (cap, m.group(1))
    return re.sub(r"!\[Figure \d+\]\(([^)]+)\)\s*\n\s*\n\*(Figure \d+\.[^\n]*)\*", fig, md)


def pandoc(exe, md):
    cmd = [exe, "--from=gfm+tex_math_gfm+tex_math_dollars", "--to=latex", "--no-highlight", "--wrap=preserve"]
    out = subprocess.run(cmd, input=md.encode("utf-8"), capture_output=True)
    if out.returncode != 0:
        sys.exit("pandoc failed: " + out.stderr.decode("utf-8", "replace"))
    return out.stdout.decode("utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pandoc", default=shutil.which("pandoc"))
    ap.add_argument("--tectonic", default=shutil.which("tectonic"))
    args = ap.parse_args()
    if not args.pandoc:
        ap.error("supply --pandoc (and --tectonic to compile)")
    text = open(SRC, encoding="utf-8").read()
    title, subtitle, byline, note, abstract, body = split_source(text)
    os.makedirs(os.path.join(OUT, "figures"), exist_ok=True)
    for f in sorted(os.listdir(os.path.join(ROOT, "paper", "figures"))):
        if f.endswith(".png"):
            shutil.copyfile(os.path.join(ROOT, "paper", "figures", f), os.path.join(OUT, "figures", f))
    # byline[0]: "Name, affiliation ... Correspondence: address";  the other lines become a note under the title
    who, _, mail = byline[0].partition("Correspondence:")
    name, _, affiliation = who.strip().rstrip(".").partition(",")
    tex = lambda s: pandoc(args.pandoc, s).strip()
    author = "%s%s%s %s%s%s %stexttt{%s}" % (tex(name), BS, BS, tex(affiliation.strip()), BS, BS, BS,
                                              mail.strip().replace("_", BS + "_"))
    status = " ".join(tex(b) for b in byline[1:])
    doc = [PREAMBLE,
           "%stitle{%s%s%s[0.7em]%slarge %s}" % (BS, tex(title), BS, BS, BS, tex(subtitle)),
           "%sauthor{%s}" % (BS, author),
           "%sdate{}" % BS,
           "%sbegin{document}" % BS, "%smaketitle" % BS,
           "%svspace{-2.5em}%sbegin{center}%ssmall %s%send{center}" % (BS, BS, BS, status, BS),
           pandoc(args.pandoc, note),
           "%sbegin{abstract}" % BS, pandoc(args.pandoc, abstract), "%send{abstract}" % BS,
           fit_tables(pandoc(args.pandoc, prepare(body))), "%send{document}" % BS, ""]
    out = "\n".join(doc)
    tex_path = os.path.join(OUT, "spectral-floor.tex")
    open(tex_path, "w", encoding="utf-8", newline="\n").write(out)
    record = {"source": "paper/spectral-floor.md",
              "source_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
              "tex_sha256": hashlib.sha256(out.encode("utf-8")).hexdigest(),
              "engine": "XeLaTeX (compiled here with Tectonic)",
              "pandoc": subprocess.check_output([args.pandoc, "--version"], text=True).splitlines()[0]}
    print("wrote", tex_path, len(out), "bytes")
    if args.tectonic:
        run = subprocess.run([args.tectonic, "--untrusted", "--keep-logs", "spectral-floor.tex"], cwd=OUT,
                             capture_output=True, text=True, encoding="utf-8", errors="replace")
        log = run.stdout + run.stderr
        open(os.path.join(OUT, "tectonic-output.log"), "w", encoding="utf-8", newline="\n").write(log)
        if run.returncode != 0:
            print(log[-3000:])
            sys.exit("tectonic failed")
        pdf = os.path.join(OUT, "spectral-floor.pdf")
        record["tectonic"] = subprocess.check_output([args.tectonic, "--version"], text=True).strip()
        record["pdf_sha256"] = hashlib.sha256(open(pdf, "rb").read()).hexdigest()
        record["pdf_bytes"] = os.path.getsize(pdf)
        over = sorted(set(re.findall(r"Overfull \\hbox \(([0-9.]+)pt too wide\)", log)), key=float)
        missing = sorted(set(re.findall(r'could not represent character "(.)"', log)))
        record["overfull_boxes_pt"] = over
        record["missing_characters"] = missing
        print("wrote", pdf, record["pdf_bytes"], "bytes; overfull (pt):", over[-6:], "missing characters:", missing)
    # the source archive for arXiv: the TeX file, the figures it uses, and the compiler choice
    import zipfile
    readme = {"spec_version": 1, "process": {"compiler": "xelatex"},
              "sources": [{"filename": "spectral-floor.tex", "usage": "toplevel"}], "texlive_version": 2025}
    members = [("00README.json", (json.dumps(readme, indent=2) + "\n").encode("utf-8")),
               ("spectral-floor.tex", out.encode("utf-8"))]
    used = sorted(set(re.findall(r"includegraphics(?:\[[^\]]*\])?\{(figures/[^}]+)\}", out)))
    for f in used:
        members.append((f, open(os.path.join(OUT, f), "rb").read()))
    zpath = os.path.join(OUT, "arxiv-source.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in members:
            info = zipfile.ZipInfo(name, date_time=(2026, 11, 9, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    record["arxiv_source_zip"] = {"files": [n for n, _ in members], "bytes": os.path.getsize(zpath),
                                  "sha256": hashlib.sha256(open(zpath, "rb").read()).hexdigest()}
    print("wrote", zpath, record["arxiv_source_zip"]["bytes"], "bytes:", ", ".join(n for n, _ in members))
    json.dump(record, open(os.path.join(OUT, "build-record.json"), "w"), indent=1)


if __name__ == "__main__":
    main()
